import { rgb } from "pdf-lib";

import { PdfContext } from "./pdfContext";

type FooterProps = {
    pageNumber: number;
};

export function drawFooter(
    ctx: PdfContext,
    { pageNumber }: FooterProps,
) {
    const { page, font } = ctx;

    const footerY = 25;

    // separator line
    page.drawLine({
        start: {
            x: ctx.margin,
            y: footerY + 18,
        },
        end: {
            x: ctx.pageWidth - ctx.margin,
            y: footerY + 18,
        },
        thickness: 0.8,
        color: rgb(.82, .82, .82),
    });

    // left text
    page.drawText(
        "Generated by Assistly",
        {
            x: ctx.margin,
            y: footerY,
            size: 9,
            font,
            color: rgb(.45, .45, .45),
        },
    );

    // page number
    const pageText = `Page ${pageNumber}`;

    page.drawText(
        pageText,
        {
            x:
                ctx.pageWidth -
                ctx.margin -
                font.widthOfTextAtSize(pageText, 9),
            y: footerY,
            size: 9,
            font,
            color: rgb(.45, .45, .45),
        },
    );
}